// Writes src/server/seo/page-dates.gen.ts: for each static document page, the day (UTC) of the last commit that touched
// the files the page renders, the sitemap's `lastmod` (W8 item 12b). `bun run build` runs it first, so a deployed
// sitemap carries the dates of the commit it was built from. A shallow clone or a checkout without git keeps the
// committed file as it is: a clone cut at its tip would date every page the day of the clone.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** A file or folder of the app, or one top-level section of the string table (`strings.ts`). */
type Source = string | { file: string; section: string };

const STRINGS = "src/lib/strings.ts";
const LEGAL_IDENTITY = "src/lib/legal-identity.ts";
const route = (name: string): string => `src/routes/_site.${name}.tsx`;

/**
 * The files each document page renders. A file shared by every page (`strings.ts`, `seo-copy.ts`, `config/site.ts`)
 * is named only by the section the page owns, or not at all: dating every page by it would date them all by any edit.
 */
export const pageSources: Readonly<Record<string, readonly Source[]>> = {
  "/about": [route("about")],
  "/accessibility": [route("accessibility")],
  "/contact": [route("contact"), "src/components/forms/contact-form.tsx"],
  "/cookies": [
    route("cookies"),
    "src/config/cookies.ts",
    LEGAL_IDENTITY,
    { file: STRINGS, section: "cookies" },
  ],
  "/editorial-standard": [route("editorial-standard"), "src/data/exposure.ts"],
  "/exposure": [route("exposure"), "src/data/exposure.ts"],
  "/faq": [route("faq"), "src/data/faq.ts"],
  "/legal": [route("legal"), LEGAL_IDENTITY],
  "/place-notes": [
    route("place-notes"),
    "src/components/forms/newsletter-form.tsx",
    { file: STRINGS, section: "newsletter" },
  ],
  "/privacy": [
    route("privacy"),
    "src/domain/retention.ts",
    LEGAL_IDENTITY,
    { file: STRINGS, section: "privacy" },
  ],
  "/submit": [route("submit"), "src/components/forms/submit"],
  "/terms": [route("terms"), LEGAL_IDENTITY],
};

export type Git = (args: string[]) => string;

const isoDay = (seconds: number): string => new Date(seconds * 1000).toISOString().slice(0, 10);

/** The day of the newest commit among the `%ct` lines of a `git log` answer, or undefined when it printed none. */
function newestDay(output: string): string | undefined {
  const stamps = output
    .split("\n")
    .filter((line) => /^\d{9,}$/.test(line.trim()))
    .map(Number);
  return stamps.length === 0 ? undefined : isoDay(Math.max(...stamps));
}

/** The day of the last commit that touched a source, UTC; undefined when git has none for it. */
export function lastCommitDay(git: Git, source: Source): string | undefined {
  if (typeof source === "string") {
    return newestDay(git(["log", "-1", "--format=%ct", "--", source]));
  }
  // `-L` takes POSIX regular expressions: `[{]` is a literal brace. The block ends at the first line of two spaces and
  // a closing brace, which is how `strings.ts` closes each of its top-level sections.
  const range = `/^  ${source.section}: [{]/,/^  [}],/:${source.file}`;
  return newestDay(git(["log", "-L", range, "--format=%ct", "-s"]));
}

/**
 * The date of each page: the newest of its sources, never later than `now`. A page none of whose sources has a commit
 * is left out, and the sitemap lists it with no `lastmod`.
 */
export function resolvePageDates(
  git: Git,
  now: Date,
  sources: Readonly<Record<string, readonly Source[]>> = pageSources,
): Record<string, string> {
  const today = now.toISOString().slice(0, 10);
  const dates: Record<string, string> = {};
  for (const [path, files] of Object.entries(sources)) {
    const days = files.flatMap((source) => lastCommitDay(git, source) ?? []);
    const newest = days.sort().at(-1);
    if (newest !== undefined) dates[path] = newest > today ? today : newest;
  }
  return dates;
}

export function renderPageDates(dates: Readonly<Record<string, string>>): string {
  const rows = Object.entries(dates)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([path, day]) => `  "${path}": "${day}",`);
  return [
    "// Generated by scripts/gen-page-dates.ts from the git history of each page's files. Do not edit.",
    "// Regenerate with: bun run scripts/gen-page-dates.ts (`bun run build` does it first).",
    "",
    "/** The day each static document page last changed, the sitemap's `lastmod` (W8 item 12b). */",
    "export const pageDates: Readonly<Record<string, string>> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const git: Git = (args) =>
    execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  const target = new URL("../src/server/seo/page-dates.gen.ts", import.meta.url);
  let shallow = "true";
  try {
    shallow = git(["rev-parse", "--is-shallow-repository"]).trim();
  } catch {
    // no git here: the committed file stays
  }
  if (shallow !== "false") {
    process.stdout.write("gen-page-dates: no full git history here, the committed dates stay\n");
  } else {
    const text = renderPageDates(resolvePageDates(git, new Date()));
    if (readFileSync(target, "utf8") !== text) writeFileSync(target, text);
  }
}
