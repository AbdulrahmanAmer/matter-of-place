// `bun run scripts/gen-action-roles.mjs`: writes a new supabase/migrations/<ts>_action_roles.sql that upserts one
// `action_roles` row per action of the matrix in src/server/lib/authz.ts, the copy `write_audit` checks (invariant 18,
// DB-04). Run it in the commit that changes the matrix; tests/unit/action-roles.sync.test.ts fails until then.
// Rows are only upserted, never deleted, so a file generated on a branch that lacks another lane's group cannot
// remove that group's rows.
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { matrix } from "../src/server/lib/authz.ts";
import { migrationFiles, migrationVersion } from "./lib/push-guard.mjs";

const MIGRATIONS = fileURLToPath(new URL("../supabase/migrations/", import.meta.url));

/** @param {string} text */
const quoted = (text) => `'${text.replaceAll("'", "''")}'`;

/**
 * The UTC time as the 14 digits of a migration name, moved past the newest existing file when the clock is behind it.
 * @param {string[]} files
 * @returns {string}
 */
function nextVersion(files) {
  const now = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
  const newest = files.flatMap((file) => migrationVersion(file) ?? []).at(-1);
  return newest !== undefined && now <= newest ? String(BigInt(newest) + 1n) : now;
}

function main() {
  const rows = [...matrix]
    .sort((a, b) => (a.action < b.action ? -1 : 1))
    .map((entry) => {
      const roles = entry.roles.map(quoted).join(", ");
      return `  (${quoted(entry.action)}, array[${roles}]::public.app_role[], ${String(entry.humanOnly === true)})`;
    });
  const file = `${nextVersion(migrationFiles(readdirSync(MIGRATIONS)))}_action_roles.sql`;
  writeFileSync(
    `${MIGRATIONS}${file}`,
    "-- down: re-run bun run scripts/gen-action-roles.mjs from the previous commit of src/server/lib/permissions\n" +
      "set lock_timeout = '5s';\n\n" +
      "-- Generated by scripts/gen-action-roles.mjs from the matrix of src/server/lib/authz.ts. Never edit by hand.\n" +
      "insert into public.action_roles (action, roles, human_only)\nvalues\n" +
      `${rows.join(",\n")}\n` +
      "on conflict (action) do update set roles = excluded.roles, human_only = excluded.human_only;\n",
  );
  console.log(`wrote supabase/migrations/${file} ${String(rows.length)} actions`);
}

main();
