// Copies the owner-approved Property Exposure data out of the codebase (read-only) so the
// partner video and deck quote it verbatim. Run with bun (it imports the .ts file directly):
//   bun shared/extract-exposure.mjs  ->  shared/exposure.json + shared/exposure.js (window.EXPOSURE)
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as X from "../../app/src/data/exposure.ts";

const here = dirname(fileURLToPath(import.meta.url));
const data = {
  offerings: X.offerings,
  programmatic: X.programmatic,
  selectionSteps: X.selectionSteps,
  editorialQualities: X.editorialQualities,
  exposureFaq: X.exposureFaq,
};
writeFileSync(join(here, "exposure.json"), JSON.stringify(data, null, 2) + "\n");
writeFileSync(join(here, "exposure.js"), "// Generated by extract-exposure.mjs from src/data/exposure.ts. Do not edit.\nwindow.EXPOSURE = " + JSON.stringify(data, null, 2) + ";\n");
console.log(`offerings ${data.offerings.length}, steps ${data.selectionSteps.length}, qualities ${data.editorialQualities.length}, faq ${data.exposureFaq.length}`);
